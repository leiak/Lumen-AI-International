/**
 * 商家门户的对外视图 DTO (Iteration 4.5C-2).
 *
 * <p><b>为什么单独一个包</b>: 仓内既有的 finance DTO (如 {@code AdjustmentDtos}、
 * {@code InvoiceDtos}) 是<b>管理端</b>的入参 / 出参契约 —— 它们描述"财务内部怎么
 * 调规则、调单据", 字段取舍以内部流程完整为准。而本包里的 DTO 是<b>对外</b>的:
 * 它们会被序列化给门户外的第三方商家看。
 *
 * <p>两者的安全边界不同, 所以不该混在一个包里:
 * <ul>
 *   <li>管理端 DTO 按需暴露内部字段 (规则 id、审批人 id、错误栈), 因为调用者是
 *       自己的财务系统</li>
 *   <li>门户 DTO 走"手工映射 + 字段白名单", 实体里任何没显式出现在 record 组件里的
 *       字段都到不了商家眼前。映射函数是这张网的唯一收口处</li>
 * </ul>
 *
 * <p>放一个包不是为了好看, 是为了让"这段代码会不会泄漏内部字段"这个问题有一个
 * 可以用包名回答的答案 —— 在 {@code dto} 根包里的 DTO 默认按"内部契约"对待, 在
 * {@code dto.portal} 里的默认按"对外契约"对待。
 */
package com.lumen.finance.dto.portal;
